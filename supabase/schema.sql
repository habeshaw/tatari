-- 7. Type-Safe Dynamic Foreign-Key Migration (Auto-matches existing uuid or bigint primary keys)
DO $tatari_migration$
DECLARE
  v_users_id_type TEXT;
  v_jobs_id_type TEXT;
  v_cats_id_type TEXT;
  v_srcs_id_type TEXT;
  v_prods_id_type TEXT;
  v_has_jobs_created_at BOOLEAN;
  v_col TEXT;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod) INTO v_users_id_type
  FROM pg_attribute a
  JOIN pg_class c ON c.oid = a.attrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relname = 'users' AND a.attname = 'id' AND NOT a.attisdropped;
  v_users_id_type := COALESCE(v_users_id_type, 'uuid');

  SELECT format_type(a.atttypid, a.atttypmod) INTO v_jobs_id_type
  FROM pg_attribute a
  JOIN pg_class c ON c.oid = a.attrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relname = 'jobs' AND a.attname = 'id' AND NOT a.attisdropped;
  v_jobs_id_type := COALESCE(v_jobs_id_type, 'uuid');

  SELECT format_type(a.atttypid, a.atttypmod) INTO v_cats_id_type
  FROM pg_attribute a
  JOIN pg_class c ON c.oid = a.attrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relname = 'job_categories' AND a.attname = 'id' AND NOT a.attisdropped;
  v_cats_id_type := COALESCE(v_cats_id_type, 'bigint');

  SELECT format_type(a.atttypid, a.atttypmod) INTO v_srcs_id_type
  FROM pg_attribute a
  JOIN pg_class c ON c.oid = a.attrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relname = 'job_sources' AND a.attname = 'id' AND NOT a.attisdropped;
  v_srcs_id_type := COALESCE(v_srcs_id_type, 'bigint');

  SELECT format_type(a.atttypid, a.atttypmod) INTO v_prods_id_type
  FROM pg_attribute a
  JOIN pg_class c ON c.oid = a.attrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relname = 'digital_products' AND a.attname = 'id' AND NOT a.attisdropped;
  v_prods_id_type := COALESCE(v_prods_id_type, 'uuid');

  -- Add FK columns to public.jobs matching exact existing PK types
  EXECUTE format('ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS category_id %s REFERENCES public.job_categories(id) ON DELETE SET NULL', v_cats_id_type);
  EXECUTE format('ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS source_id %s REFERENCES public.job_sources(id) ON DELETE SET NULL', v_srcs_id_type);
  EXECUTE format('ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS employer_id %s REFERENCES public.users(id) ON DELETE SET NULL', v_users_id_type);

  -- Automated Job Collection Logs
  EXECUTE format($sql$
    CREATE TABLE IF NOT EXISTS public.job_collection_logs (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      source_id %s NOT NULL REFERENCES public.job_sources(id) ON DELETE CASCADE,
      collection_started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      collection_completed_at TIMESTAMPTZ,
      jobs_found INTEGER NOT NULL DEFAULT 0,
      jobs_added INTEGER NOT NULL DEFAULT 0,
      jobs_updated INTEGER NOT NULL DEFAULT 0,
      duplicates_found INTEGER NOT NULL DEFAULT 0,
      errors TEXT,
      collection_status TEXT NOT NULL CHECK (collection_status IN ('success', 'partial', 'failed', 'running'))
    )
  $sql$, v_srcs_id_type);

  -- Internal Job Applications (for Tatari-published jobs)
  EXECUTE format($sql$
    CREATE TABLE IF NOT EXISTS public.job_applications (
      id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      job_id %s NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
      seeker_id %s REFERENCES public.users(id) ON DELETE SET NULL,
      applicant_name TEXT NOT NULL,
      applicant_email TEXT NOT NULL,
      applicant_phone TEXT NOT NULL,
      cover_note TEXT NOT NULL,
      cv_summary TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'submitted',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  $sql$, v_jobs_id_type, v_users_id_type);

  -- Saved Jobs & Bookmarks
  EXECUTE format($sql$
    CREATE TABLE IF NOT EXISTS public.saved_jobs (
      id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      user_id %s NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
      job_id %s NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (user_id, job_id)
    )
  $sql$, v_users_id_type, v_jobs_id_type);

  -- Job Alerts
  EXECUTE format($sql$
    CREATE TABLE IF NOT EXISTS public.job_alerts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id %s NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
      email TEXT NOT NULL,
      category_id %s REFERENCES public.job_categories(id) ON DELETE SET NULL,
      location TEXT,
      keywords TEXT,
      job_origin_pref TEXT NOT NULL DEFAULT 'all' CHECK (job_origin_pref IN ('all', 'external', 'tatari')),
      frequency TEXT NOT NULL DEFAULT 'instant' CHECK (frequency IN ('instant', 'daily')),
      active BOOLEAN NOT NULL DEFAULT TRUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  $sql$, v_users_id_type, v_cats_id_type);

  -- Notifications
  EXECUTE format($sql$
    CREATE TABLE IF NOT EXISTS public.notifications (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id %s NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
      title TEXT NOT NULL,
      message TEXT NOT NULL,
      link_slug TEXT,
      is_read BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  $sql$, v_users_id_type);

  -- Digital Store Orders
  EXECUTE format($sql$
    CREATE TABLE IF NOT EXISTS public.digital_orders (
      id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      product_id %s NOT NULL REFERENCES public.digital_products(id) ON DELETE CASCADE,
      user_id %s NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
      buyer_name TEXT NOT NULL,
      buyer_email TEXT NOT NULL,
      payment_method TEXT NOT NULL,
      payment_ref TEXT NOT NULL,
      receipt_note TEXT,
      amount_etb INTEGER NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      rejection_reason TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      verified_at TIMESTAMPTZ
    )
  $sql$, v_prods_id_type, v_users_id_type);

  -- Dynamically copy from any legacy column names on existing public.jobs tables
  FOR v_col IN
    SELECT column_name FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'jobs'
      AND column_name IN ('job_title', 'position', 'role_title', 'name', 'heading')
    LIMIT 1
  LOOP
    EXECUTE format('UPDATE public.jobs SET title = NULLIF(BTRIM(%I::text), '''') WHERE title IS NULL OR title = ''''', v_col);
  END LOOP;

  FOR v_col IN
    SELECT column_name FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'jobs'
      AND column_name IN ('company', 'organization', 'employer_name', 'employer')
    LIMIT 1
  LOOP
    EXECUTE format('UPDATE public.jobs SET company_name = NULLIF(BTRIM(%I::text), '''') WHERE company_name IS NULL OR company_name = ''''', v_col);
  END LOOP;

  FOR v_col IN
    SELECT column_name FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'jobs'
      AND column_name IN ('city', 'work_location', 'region', 'place')
    LIMIT 1
  LOOP
    EXECUTE format('UPDATE public.jobs SET location = COALESCE(NULLIF(BTRIM(%I::text), ''''), location) WHERE location = ''Ethiopia'' OR location IS NULL', v_col);
  END LOOP;

  FOR v_col IN
    SELECT column_name FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'jobs'
      AND column_name IN ('job_description', 'details', 'summary', 'body')
    LIMIT 1
  LOOP
    EXECUTE format('UPDATE public.jobs SET description = COALESCE(NULLIF(BTRIM(%I::text), ''''), description) WHERE description = '''' OR description IS NULL', v_col);
  END LOOP;

  -- Backfill existing Tatari job rows safely via dynamic SQL
  EXECUTE $sql$
    UPDATE public.jobs
    SET
      job_origin = COALESCE(NULLIF(job_origin, ''), 'tatari'),
      dedupe_key = COALESCE(NULLIF(dedupe_key, ''), id::text),
      slug = COALESCE(
        NULLIF(slug, ''),
        TRIM(BOTH '-' FROM LOWER(REGEXP_REPLACE(COALESCE(NULLIF(title, ''), 'job'), '[^a-zA-Z0-9]+', '-', 'g'))) || '-' || LEFT(REPLACE(id::text, '-', ''), 12)
      )
    WHERE slug IS NULL OR slug = '' OR dedupe_key IS NULL OR dedupe_key = '' OR job_origin IS NULL
  $sql$;

  EXECUTE $sql$
    UPDATE public.job_categories
    SET slug = TRIM(BOTH '-' FROM LOWER(REGEXP_REPLACE(COALESCE(name, 'category'), '[^a-zA-Z0-9]+', '-', 'g')))
    WHERE slug IS NULL OR slug = ''
  $sql$;

  SELECT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'jobs' AND column_name = 'created_at'
  ) INTO v_has_jobs_created_at;

  IF v_has_jobs_created_at THEN
    EXECUTE 'UPDATE public.jobs SET published_at = COALESCE(published_at, created_at, NOW()) WHERE published_at IS NULL';
  END IF;
END $tatari_migration$;

