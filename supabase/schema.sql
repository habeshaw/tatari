-- TATARI — Ethiopian Job Discovery & Digital Store
-- Idempotent & Backward-Compatible Supabase PostgreSQL Migration Schema
-- Safe to run on both brand-new Supabase projects AND existing TATARI databases (uuid or bigint PKs).

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Standardized Ethiopian Job Categories
CREATE TABLE IF NOT EXISTS public.job_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  slug TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.job_categories ADD COLUMN IF NOT EXISTS name TEXT;
ALTER TABLE public.job_categories ADD COLUMN IF NOT EXISTS slug TEXT;

-- 2. External Ethiopian Job Sources (Ethiojobs, GeezJobs, Ezega Jobs, EthiopianWork, Gov, Career Pages)
CREATE TABLE IF NOT EXISTS public.job_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_name TEXT NOT NULL,
  website_url TEXT NOT NULL,
  feed_url TEXT NOT NULL,
  collection_method TEXT NOT NULL CHECK (collection_method IN ('rss', 'json_api', 'html_directory', 'partner_feed')),
  collection_frequency TEXT NOT NULL DEFAULT 'every_6h' CHECK (collection_frequency IN ('hourly', 'every_6h', 'daily', 'manual')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'error')),
  robots_respect BOOLEAN NOT NULL DEFAULT TRUE,
  rate_limit_ms INTEGER NOT NULL DEFAULT 1200,
  last_collected_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

